#include "push_swap.h"

void	sort_stack(t_stack *a, t_stack *b)
{
	if (!a || a->size < 2 || is_sorted(a))
		return ;
	if (a->size <= 5)
		sort_small(a, b);
	else
		radix_sort(a, b);
}
